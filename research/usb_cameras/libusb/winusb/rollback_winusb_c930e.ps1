# rollback_winusb_c930e.ps1 - undo install_winusb_c930e.ps1 (or a Zadig/libwdi install). ELEVATED.
#
#   pwsh -File research/usb_cameras/libusb/winusb/run_elevated.ps1 -Action rollback
#
# Steps:
#   1. reads results/windows/<host>/winusb_install/prestate.json (written by the installer);
#   2. if any libwdi/Zadig driver package for VID_046D&PID_0843 exists in the driver store
#      (Provider "libwdi", or an oem*.inf whose original name is from libwdi), deletes it with
#      pnputil /delete-driver <oem#.inf> /uninstall /force, and removes the libwdi self-signed
#      certificate "CN=USB\VID_046D&PID_0843* (libwdi autogenerated)" from LocalMachine\Root and
#      LocalMachine\TrustedPublisher (libwdi pki.c adds it to both);
#   3. removes the device node (pnputil /remove-device <id> /subtree) and re-enumerates
#      (pnputil /scan-devices) so PnP re-ranks drivers: the inbox winusb.inf has no hardware-ID
#      match, so the previous best-ranked package (here oem74.inf = Logitech luvc1564c.inf ->
#      usbccgp, children usbvideo/usbaudio) is chosen again;
#   4. compares service/INF per device with prestate.json and writes rollback_result.json.
param([string]$InstanceId)
$ErrorActionPreference = "Stop"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$outDir = [IO.Path]::GetFullPath((Join-Path $here "..\..\results\windows\$env:COMPUTERNAME\winusb_install"))
New-Item -ItemType Directory -Force $outDir | Out-Null
$stamp = (Get-Date).ToUniversalTime().ToString("yyyyMMddTHHmmssZ")
Start-Transcript -Path (Join-Path $outDir "rollback_$stamp.log") | Out-Null
$result = [ordered]@{ test = "winusb_rollback_c930e"; platform = "windows"; hostname = $env:COMPUTERNAME
  utc_started = (Get-Date).ToUniversalTime().ToString("o"); command = $MyInvocation.Line; steps = @() }
function Step($s) { $script:result.steps += $s; Write-Host $s }
try {
  $isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
  if (-not $isAdmin) { throw "must run elevated (use run_elevated.ps1)" }
  $preFile = Join-Path $outDir "prestate.json"
  $pre = if (Test-Path $preFile) { Get-Content -Raw $preFile | ConvertFrom-Json } else { $null }
  if (-not $InstanceId) {
    $InstanceId = if ($pre) { $pre.parent_instance_id } else {
      (Get-PnpDevice -PresentOnly | Where-Object { $_.InstanceId -like 'USB\VID_046D&PID_0843\*' } | Select-Object -First 1).InstanceId }
  }
  if (-not $InstanceId) { throw "no C930e parent instance id (plug the camera in)" }
  $result.instance_id = $InstanceId

  # --- libwdi / Zadig leftovers ---
  # only packages whose provider is libwdi AND whose hardware IDs include this camera
  $drivers = pnputil /enum-drivers /ids | Out-String
  $blocks = $drivers -split "(?m)^\s*\r?$"
  foreach ($b in $blocks) {
    if ($b -match "Published Name:\s+(oem\d+\.inf)") {
      $oem = $Matches[1]
      if ($b -match "Provider Name:\s+libwdi" -and $b -match "VID_046D&PID_0843") {
        Step "deleting libwdi driver package $oem"
        Step (pnputil /delete-driver $oem /uninstall /force | Out-String)
      }
    }
  }
  foreach ($store in @("Root", "TrustedPublisher")) {
    Get-ChildItem "Cert:\LocalMachine\$store" | Where-Object { $_.Subject -like 'CN=USB\VID_046D&PID_0843*(libwdi autogenerated)*' } | ForEach-Object {
      Step "removing certificate '$($_.Subject)' ($($_.Thumbprint)) from LocalMachine\$store"
      Remove-Item -Path "Cert:\LocalMachine\$store\$($_.Thumbprint)" -Force
    }
  }

  # --- remove devnode and re-enumerate ---
  Step "pnputil /remove-device $InstanceId /subtree"
  Step (pnputil /remove-device "$InstanceId" /subtree | Out-String)
  Start-Sleep -Seconds 2
  Step "pnputil /scan-devices"
  Step (pnputil /scan-devices | Out-String)
  Start-Sleep -Seconds 5

  $now = @(Get-PnpDevice -PresentOnly | Where-Object { $_.InstanceId -like 'USB\VID_046D&PID_0843*' }) | ForEach-Object {
    [ordered]@{ instance_id = $_.InstanceId; class = $_.Class; status = "$($_.Status)"
      service = (Get-PnpDeviceProperty -InstanceId $_.InstanceId -KeyName DEVPKEY_Device_Service -ErrorAction SilentlyContinue).Data
      inf = (Get-PnpDeviceProperty -InstanceId $_.InstanceId -KeyName DEVPKEY_Device_DriverInfPath -ErrorAction SilentlyContinue).Data }
  }
  $result.poststate = @($now)
  $mismatch = @()
  if ($pre) {
    foreach ($d in $pre.devices) {
      $n = $now | Where-Object { $_.instance_id -eq $d.instance_id }
      if (-not $n) { $mismatch += "missing: $($d.instance_id)"; continue }
      if ($n.service -ne $d.service -or $n.inf -ne $d.inf) { $mismatch += "$($d.instance_id): service $($n.service) inf $($n.inf) (was $($d.service) $($d.inf))" }
    }
  }
  $result.mismatches = $mismatch
  $parentSvc = ($now | Where-Object { $_.instance_id -notlike '*&MI_*' } | Select-Object -First 1).service
  $result.outcome = if ($mismatch.Count -eq 0 -and $parentSvc -ne "WinUSB") { "OK: restored ($parentSvc)" } else { "CHECK: parent service '$parentSvc'; mismatches: $($mismatch -join '; ')" }
} catch {
  $result.outcome = "ERROR: $($_.Exception.Message)"
} finally {
  $result.utc_finished = (Get-Date).ToUniversalTime().ToString("o")
  $result | ConvertTo-Json -Depth 6 | Set-Content -Encoding utf8 (Join-Path $outDir "rollback_result.json")
  Write-Host $result.outcome
  Stop-Transcript | Out-Null
  "DONE" | Set-Content (Join-Path $outDir "rollback.done")
}
