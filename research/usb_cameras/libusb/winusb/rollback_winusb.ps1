# rollback_winusb.ps1 - undo install_winusb.ps1 (or a Zadig/libwdi install) on one or more cameras. ELEVATED.
# Camera-agnostic successor of rollback_winusb_c930e.ps1 (unchanged, still works for the C930e).
#
#   pwsh -File research/usb_cameras/libusb/winusb/run_elevated_winusb.ps1 -Action rollback -Device 046D:085C,4C4A:4A55
#   (no -Device: every parent recorded in results/windows/<host>/winusb_multi/prestate.json)
#
# Per device:
#   1. prestate entry from winusb_multi/prestate.json (keyed by parent instance id); for the C930e also the
#      legacy winusb_install/prestate.json;
#   2. deletes libwdi/Zadig driver packages whose hardware IDs include this VID/PID (pnputil /delete-driver
#      /uninstall /force) and the "CN=USB\VID_xxxx&PID_yyyy* (libwdi autogenerated)" certificates in
#      LocalMachine\Root and \TrustedPublisher (none exist for the inbox route; kept for Zadig installs);
#   3. pnputil /remove-device <parent> /subtree.
# Then ONE pnputil /scan-devices, and up to -WaitS seconds for every parent to come back with a non-WinUSB service.
# Post-check per function key (parent, MI_00, MI_02, ...): service and INF must equal the prestate (case-insensitive).
# Child instance ids are expected to change on re-enumeration (C930e: 8&39DEC205&0&0000 -> 8&39DEC205&1&0000);
# they are reported under instance_id_changes and are NOT a mismatch.
# After rollback the C930e needed a physical replug before Media Foundation delivered frames: replug, then
# verify_winusb.ps1 -Device ... -Mf.
# Writes winusb_multi/rollback_result.json, rollback_<stamp>.log, rollback.done.
param(
  [string[]]$Device,
  [int]$WaitS = 20,
  [string]$OutDir
)
$ErrorActionPreference = "Stop"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
. (Join-Path $here "winusb_common.ps1")
if (-not $OutDir) { $OutDir = Get-WinUsbResultsDir $here }
New-Item -ItemType Directory -Force $OutDir | Out-Null
$stamp = (Get-Date).ToUniversalTime().ToString("yyyyMMddTHHmmssZ")
Start-Transcript -Path (Join-Path $OutDir "rollback_$stamp.log") | Out-Null
$specs = if ($Device) { Split-DeviceSpecs $Device } else { @() }
$result = [ordered]@{ test = "winusb_rollback"; platform = "windows"; hostname = $env:COMPUTERNAME
  utc_started = (Get-Date).ToUniversalTime().ToString("o"); command = "rollback_winusb.ps1$(if ($specs) { ' -Device ' + ($specs -join ',') })"
  is_admin = (Test-IsAdmin); steps = @(); devices = @() }
function Step($s) { $script:result.steps += "$s"; Write-Host $s }
try {
  if (-not $result.is_admin) { throw "must run elevated (use run_elevated_winusb.ps1)" }
  $store = Read-Prestates (Join-Path $OutDir "prestate.json")
  # ---- which parents ----
  $parents = @()
  if ($specs) {
    foreach ($s in $specs) {
      $hit = @($store.devices.Keys | Where-Object { $_ -eq $s -or (Get-VidPidOf $_) -eq $s.ToUpper() })
      if ($hit.Count -eq 1) { $parents += $hit[0] }
      elseif ($hit.Count -gt 1) { throw "several stored parents match $s ($($hit -join ', ')); pass the instance id" }
      else { $parents += (Resolve-ParentInstance $s) }
    }
  } else { $parents = @($store.devices.Keys) }
  if (-not $parents) { throw "nothing to roll back (no -Device and no entries in prestate.json)" }
  $drivers = pnputil /enum-drivers /ids | Out-String
  $blocks = $drivers -split "(?m)^\s*\r?$"
  foreach ($parent in $parents) {
    $r = [ordered]@{ parent_instance_id = $parent; vid_pid = (Get-VidPidOf $parent) }
    $pre = if ($store.devices.Contains($parent)) { $store.devices[$parent] } else { Read-LegacyPrestate $here $parent }
    $r.prestate_source = if ($store.devices.Contains($parent)) { "winusb_multi/prestate.json" } elseif ($pre) { $pre.source } else { $null }
    $r.prestate = $pre
    $r.state_before_rollback = Get-Family $parent
    # ---- libwdi / Zadig leftovers for this VID/PID ----
    $vp = $r.vid_pid -split ":"
    $hw = "VID_$($vp[0])&PID_$($vp[1])"
    foreach ($b in $blocks) {
      if ($b -match "Published Name:\s+(oem\d+\.inf)") {
        $oem = $Matches[1]
        if ($b -match "Provider Name:\s+libwdi" -and $b -match [regex]::Escape($hw)) {
          Step "deleting libwdi driver package $oem ($hw)"
          Step (pnputil /delete-driver $oem /uninstall /force | Out-String)
        }
      }
    }
    foreach ($st in @("Root", "TrustedPublisher")) {
      Get-ChildItem "Cert:\LocalMachine\$st" | Where-Object { $_.Subject -like "CN=USB\$hw*(libwdi autogenerated)*" } | ForEach-Object {
        Step "removing certificate '$($_.Subject)' ($($_.Thumbprint)) from LocalMachine\$st"
        Remove-Item -Path "Cert:\LocalMachine\$st\$($_.Thumbprint)" -Force
      }
    }
    Step "pnputil /remove-device $parent /subtree"
    Step (pnputil /remove-device "$parent" /subtree | Out-String)
    $result.devices += $r
  }
  Start-Sleep -Seconds 2
  Step "pnputil /scan-devices"
  Step (pnputil /scan-devices | Out-String)
  # ---- wait for every parent to re-appear on a non-WinUSB service ----
  $t0 = Get-Date
  do {
    Start-Sleep -Seconds 2
    $pending = @($result.devices | Where-Object {
      $d = Get-PnpDevice -InstanceId $_.parent_instance_id -ErrorAction SilentlyContinue
      -not $d -or -not $d.Present -or (Test-ServiceEq (Get-DevProp $_.parent_instance_id DEVPKEY_Device_Service) "WinUSB") -or
        @(Get-DevProp $_.parent_instance_id DEVPKEY_Device_Children).Count -lt (@($_.prestate.functions).Count - 1) })
  } while ($pending.Count -gt 0 -and ((Get-Date) - $t0).TotalSeconds -lt $WaitS)
  Start-Sleep -Seconds 2
  # ---- compare per function key ----
  $allOk = $true
  foreach ($r in $result.devices) {
    $now = Get-Family $r.parent_instance_id
    $r.poststate = $now
    $cmp = Compare-Family $r.prestate.functions $now
    $mm = @($cmp.mismatches); $idc = @($cmp.instance_id_changes); $pSvc = $cmp.parent_service
    $r.instance_id_changes = $idc
    $r.mismatches = $mm
    $r.parent_service_after = $pSvc
    $ok = $mm.Count -eq 0 -and $pSvc -and -not (Test-ServiceEq $pSvc "WinUSB")
    $r.outcome = if ($ok) { "OK: restored ($pSvc)$(if ($idc) { '; child instance ids re-generated (expected)' })" } else { "CHECK: parent service '$pSvc'; $($mm -join '; ')" }
    if (-not $ok) { $allOk = $false }
    Write-Host "$($r.parent_instance_id) -> $($r.outcome)"
  }
  $result.outcome = if ($allOk) { "OK: $($result.devices.Count) device(s) restored" } else { "CHECK: $(@($result.devices | ForEach-Object { $_.outcome }) -join ' | ')" }
  $result.next_step = "replug each camera (the C930e needed a replug before Media Foundation delivered frames), then: " +
    "pwsh -File research/usb_cameras/libusb/winusb/verify_winusb.ps1 -Device <same list> -Mf"
} catch {
  $result.outcome = "ERROR: $($_.Exception.Message)"
  $result.error_detail = "$_"
} finally {
  $result.utc_finished = (Get-Date).ToUniversalTime().ToString("o")
  $result | ConvertTo-Json -Depth 9 | Set-Content -Encoding utf8 (Join-Path $OutDir "rollback_result.json")
  Write-Host $result.outcome
  Stop-Transcript | Out-Null
  "DONE" | Set-Content (Join-Path $OutDir "rollback.done")
}
