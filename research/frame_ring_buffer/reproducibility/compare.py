r"""Compare the reproducibility re-runs with the originally reported values. NOT SkellyCam code.

Originals: the result files in baseline/results, prototypes/results, cpp/results (restored byte-for-byte after the re-run,
see restore_check.json). Re-runs: reproducibility/rerun/<same relative path> (collected by protect_originals.py collect).

Tolerance (from the task): throughput metrics (fps, payloads/s, GB/s) within 15%; same pass/fail at 5x60.
Pass at 5x60 := slowest camera >= 59.5 fps (the 60 fps target less 0.8%, which absorbs start/stop edge frames).
Latency metrics (ms) are listed with their change but are not part of the tolerance test.

Run from C:\Users\Dom\GitHub\freemocap\skellycam:
  .venv\Scripts\python.exe research\frame_ring_buffer\reproducibility\compare.py
Writes reproducibility/comparison.json and reproducibility/comparison.md.
"""
import json
import re
from pathlib import Path

FP = Path(__file__).resolve().parents[1]
HERE = Path(__file__).resolve().parent
RR = HERE / "rerun"
TOL = 0.15
PASS_FPS = 59.5


def md_table(path):
    """Return list of dict rows from every markdown table in the file (header row = first row of the table)."""
    rows, hdr = [], None
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            hdr = None
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if hdr is None:
            hdr = cells
            continue
        if all(set(c) <= set("-: ") for c in cells):
            continue
        rows.append(dict(zip(hdr, cells)))
    return rows


def num(s, i=0):
    v = re.findall(r"-?\d+(?:\.\d+)?", str(s))
    return float(v[i]) if len(v) > i else None


def chg(o, n):
    if o in (None, 0) or n is None:
        return None
    return (n - o) / o


OUT = {"tolerance": TOL, "pass_fps": PASS_FPS, "sections": {}}
MD = ["# Reproducibility comparison (generated by compare.py)", "",
      f"Throughput tolerance +/-{TOL:.0%}; pass at 5x60 = slowest camera >= {PASS_FPS} fps. "
      "Latency rows (ms) are shown for context and are not part of the tolerance test.", ""]


def add(section, rows, cols):
    OUT["sections"][section] = rows
    MD.append(f"## {section}\n")
    MD.append("| " + " | ".join(cols) + " |")
    MD.append("|" + "---|" * len(cols))
    for r in rows:
        MD.append("| " + " | ".join("" if r.get(c) is None else (f"{r[c]:+.1%}" if c.startswith("chg") and isinstance(r[c], float)
                                                                   else str(r[c])) for c in cols) + " |")
    MD.append("")


def thr_row(key, metric, o, n, kind="throughput", passcheck=False):
    c = chg(o, n)
    r = dict(row=key, metric=metric, original=o, rerun=n, chg=c, kind=kind)
    if kind == "throughput":
        r["within_tol"] = c is not None and abs(c) <= TOL
    if passcheck:
        r["pass_orig"] = o is not None and o >= PASS_FPS
        r["pass_rerun"] = n is not None and n >= PASS_FPS
        r["same_pass_fail"] = r["pass_orig"] == r["pass_rerun"]
    return r


# ---- 1. baseline e2e (real SkellyCam stack) ----
summ = {r["file"]: r for r in md_table(RR / "baseline/results/e_e2e_summary.md")}
pairs = [("e_e2e_1080p_mjpeg_ui.json", "e_e2e_1080p_mjpeg_ui_repro.json"),
         ("e_e2e_1080p_mjpeg_ui_rep2.json", "e_e2e_1080p_mjpeg_ui_repro_rep2.json"),
         ("e_e2e_1080p_memcpy_ui.json", "e_e2e_1080p_memcpy_ui_repro.json"),
         ("e_e2e_720p_mjpeg_ui.json", "e_e2e_720p_mjpeg_ui_repro.json")]
rows = []
for o, n in pairs:
    a, b = summ[o], summ[n]
    k = f"{o} vs {n}"
    rows.append(thr_row(k, "achieved fps (min cam)", num(a["achieved fps (min cam)"]), num(b["achieved fps (min cam)"]), passcheck=True))
    rows.append(thr_row(k, "UI payloads/s", num(a["UI payloads/s"]), num(b["UI payloads/s"])))
    rows.append(thr_row(k, "sensor frames never grabbed (sum 5)", num(a["sensor frames never grabbed (sum 5 cams)"]), num(b["sensor frames never grabbed (sum 5 cams)"]), kind="count"))
    rows.append(dict(row=k, metric="frames in files == recorded", original=a["frames in files == recorded"], rerun=b["frames in files == recorded"], kind="check"))
    for col, lab in [("retrieve median ms", "retrieve median ms"), ("put_frame median / p99 ms", "put_frame median ms"),
                     ("record_frame median / p99 ms", "record_frame median ms"), ("grab interval median / p99 / max ms", "grab interval median ms"),
                     ("sensor tick -> written median / p99 / max ms", "tick->written median ms")]:
        rows.append(thr_row(k, lab, num(a[col]), num(b[col]), kind="latency"))
    rows.append(thr_row(k, "tick->written p99 ms", num(a["sensor tick -> written median / p99 / max ms"], 1), num(b["sensor tick -> written median / p99 / max ms"], 1), kind="latency"))
add("baseline e2e (bench_e_e2e.py, real SkellyCam stack)", rows,
    ["row", "metric", "original", "rerun", "chg", "kind", "within_tol", "same_pass_fail"])

# ---- 2. P8 record-path prototype ----
o8 = {r["file"]: r for r in md_table(FP / "prototypes/results/p8_e2e_summary.md")}
n8 = {r["file"]: r for r in md_table(RR / "prototypes/results/p8_e2e_summary.md")}
rows = []
for f in ["p8_e2e_1080p_imdecode_msmf.json", "p8_e2e_1080p_imdecode_msmf_rep2.json",
          "p8_e2e_1080p_imdecode_off_passthrough.json", "p8_e2e_1080p_imdecode_off_passthrough_rep2.json"]:
    a, b = o8[f], n8[f]
    rows.append(thr_row(f, "per-cam fps (min)", num(a["per-cam fps (min)"]), num(b["per-cam fps (min)"]), passcheck=True))
    rows.append(thr_row(f, "UI payloads/s", num(a["UI payloads/s"]), num(b["UI payloads/s"])))
    rows.append(thr_row(f, "sensor frames never grabbed (sum)", num(a["sensor frames never grabbed (sum)"]), num(b["sensor frames never grabbed (sum)"]), kind="count"))
    rows.append(dict(row=f, metric="files decode == produced / consecutive", original=a["files decode == produced"] + "/" + a["consecutive"],
                     rerun=b["files decode == produced"] + "/" + b["consecutive"], kind="check"))
    t = "tick->written median / p99 / max ms (worst cam)"
    rows.append(thr_row(f, "tick->written median ms", num(a[t]), num(b[t]), kind="latency"))
    rows.append(thr_row(f, "tick->written p99 ms", num(a[t], 1), num(b[t], 1), kind="latency"))
    c = "CPU % cams / recorders / main"
    rows.append(thr_row(f, "recorder CPU %", num(a[c], 1), num(b[c], 1), kind="cpu"))
add("P8 end-to-end prototype (p8_e2e_proto.py)", rows,
    ["row", "metric", "original", "rerun", "chg", "kind", "within_tol", "same_pass_fail"])

# ---- 3. P6 UI path ----
rows = []
for venv in ("skellycamvenv", "benchvenv"):
    oj = json.loads((FP / f"prototypes/results/p6_ui_{venv}.json").read_text())["rows"]
    nj = {(r["size"], r["variant"]): r for r in json.loads((RR / f"prototypes/results/p6_ui_{venv}.json").read_text())["rows"]}
    for r in oj:
        m = nj.get((r["size"], r["variant"]))
        if not m:
            continue
        k = f"{r['size']} {r['variant']} ({venv})"
        rows.append(thr_row(k, "payloads/s", round(r["payloads_per_s"], 1), round(m["payloads_per_s"], 1)))
        rows.append(thr_row(k, "build median ms", r["build"]["median_ms"], m["build"]["median_ms"], kind="latency"))
        rows.append(thr_row(k, "event-loop blocked median ms", r["loop_blocked"]["median_ms"], m["loop_blocked"]["median_ms"], kind="latency"))
add("P6 UI path (p6_ui_path.py)", rows, ["row", "metric", "original", "rerun", "chg", "kind", "within_tol"])

# ---- 4. C++ vs Python ring ----
oc = json.loads((FP / "cpp/results/cpp_comparison.json").read_text())
nc = json.loads((RR / "cpp/results/cpp_comparison.json").read_text())
rows = []
nw = {r["run"]: r for r in nc["ring_write"]}
for r in oc["ring_write"]:
    m = nw.get(r["run"])
    if not m:
        continue
    rows.append(thr_row(r["run"], "slowest-camera fps", round(r["min_cam_fps"], 1), round(m["min_cam_fps"], 1)))
    rows.append(thr_row(r["run"], "put median ms", r["put_median_ms"], m["put_median_ms"], kind="latency"))
    rows.append(dict(row=r["run"], metric="verified", original=r["verified"], rerun=m["verified"], kind="check"))
ns = {r["run"]: r for r in nc["ring_spsc"]}
for r in oc["ring_spsc"]:
    m = ns.get(r["run"])
    if not m:
        continue
    rows.append(thr_row(r["run"], "slowest-camera sustained fps", round(r["min_cam_sustained_fps"], 1), round(m["min_cam_sustained_fps"], 1),
                        passcheck=r["paced"] == 60 or r["paced"] == 60.0))
    rows.append(thr_row(r["run"], "publish median ms", r["pub_median_ms"], m["pub_median_ms"], kind="latency"))
    if r["paced"]:
        rows.append(thr_row(r["run"], "publish->read median ms", r["e2e_median_ms"], m["e2e_median_ms"], kind="latency"))
    rows.append(dict(row=r["run"], metric="written/read/lost/torn", original=f"{r['frames_written']}/{r['frames_read']}/{r['lost']}/{r['torn']}",
                     rerun=f"{m['frames_written']}/{m['frames_read']}/{m['lost']}/{m['torn']}", kind="check"))
add("C++ vs Python ring (cpp/run_matrix.py ring_write, ring_spsc)", rows,
    ["row", "metric", "original", "rerun", "chg", "kind", "within_tol", "same_pass_fail"])

# ---- summary counts ----
summary = {}
for s, rs in OUT["sections"].items():
    t = [r for r in rs if r.get("kind") == "throughput"]
    summary[s] = dict(throughput_rows=len(t), within_tol=sum(1 for r in t if r.get("within_tol")),
                      outside_tol=[f"{r['row']} :: {r['metric']} {r['original']} -> {r['rerun']} ({r['chg']:+.1%})" for r in t if not r.get("within_tol")],
                      pass_fail_rows=sum(1 for r in rs if "same_pass_fail" in r),
                      pass_fail_changed=[f"{r['row']} :: {r['original']} -> {r['rerun']}" for r in rs if r.get("same_pass_fail") is False])
OUT["summary"] = summary
MD.insert(4, "## Summary\n\n```\n" + json.dumps(summary, indent=1) + "\n```\n")
(HERE / "comparison.json").write_text(json.dumps(OUT, indent=1), encoding="utf-8")
(HERE / "comparison.md").write_text("\n".join(MD), encoding="utf-8")
print(json.dumps(summary, indent=1))
