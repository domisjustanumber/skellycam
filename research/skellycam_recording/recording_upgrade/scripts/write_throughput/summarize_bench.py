"""Collect results/write_throughput/bench/**/*.json into results/write_throughput/bench/bench_summary.md.

One table per set directory (core, models, variants, intra, long, repeat, adhoc) plus the usability JSONs.
Run (repo root): .venv/Scripts/python.exe research/skellycam_recording/recording_upgrade/scripts/write_throughput/summarize_bench.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import wt_common as W  # noqa: E402


def f(x, nd=2):
    if x is None:
        return ""
    if isinstance(x, float):
        return f"{x:.{nd}f}"
    return str(x)


def write_table(rows):
    cols = ["writer", "model", "payload", "cams", "profile", "dur s", "produced", "written", "dropped", "late",
            "files", "MB/s (nominal)", "write ms p50/p99/p99.9/max", "worst-cam p99.9", "tick->written ms p99/max",
            "grab late ms p99/max", "max close s", "our CPU %/cam", "sys busy %", "MsMpEng CPU s", "disk write GB"]
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for s in rows:
        wm, tl, gl = s["write_ms_all"], s["tick_to_written_ms_all"], s["grab_lateness_ms_all"]
        disk = s.get("physical_disk_delta") or {}
        dgb = sum(v.get("write_bytes", 0) or 0 for v in disk.values() if isinstance(v, dict)) / 1e9
        ms = s.get("msmpeng_cpu_s")
        out.append("| " + " | ".join([
            s["writer"], s["model"], s["payload"], str(s["cams"]), s["profile"], f(s["duration_s"], 0),
            str(s["produced"]), str(s["written"]), str(s["dropped"]), str(s["late_ticks"]), str(s["files_written"]),
            f"{f(s['throughput_MBps_over_duration'], 1)} ({f(s['nominal_MBps'], 1)})",
            "/".join(f(wm[k], 3) for k in ("p50", "p99", "p99.9", "max")), f(s["worst_cam_write_ms_p999"], 3),
            "/".join(f(tl[k], 2) for k in ("p99", "max")), "/".join(f(gl[k], 2) for k in ("p99", "max")),
            f(s["max_close_s"], 3), f(s["our_cpu_pct_of_one_core_per_cam"], 1), f(s["system_busy_pct_all_cpus"], 1),
            f(ms, 1) if isinstance(ms, float) else str(ms), f(dgb, 2)]) + " |")
    return "\n".join(out)


def main():
    root = W.BENCH_RESULTS
    L = ["# write_throughput bench summary (generated by summarize_bench.py)\n",
         "Columns: write ms = duration of the writer.write() call per frame, all cameras pooled; tick->written = "
         "scheduled capture tick to write return; grab late = how late the camera loop picked up its tick "
         "(inloop models show writer stalls here); our CPU %/cam = all bench process CPU / duration / cams "
         "(100 = one logical CPU); sys busy % = psutil system-wide busy share of all logical CPUs; MsMpEng = "
         "Defender engine CPU seconds during the run; disk write GB = PhysicalDrive write bytes during the run "
         "(the lazy writer may still hold data at the end of short runs).\n"]
    for d in sorted(p for p in root.iterdir() if p.is_dir() and p.name != "usability"):
        rows = []
        for j in sorted(d.glob("*.json")):
            try:
                rows.append(json.loads(j.read_text())["summary"])
            except Exception as e:  # noqa: BLE001
                print("skip", j, e)
        if rows:
            rows.sort(key=lambda s: (s["payload"], s["profile"], s["cams"], s["model"], s["writer"]))
            L.append(f"\n## {d.name} ({len(rows)} cells)\n")
            L.append(write_table(rows))
    u = root / "usability"
    if u.exists():
        for j in sorted(u.glob("usability_*.json")):
            r = json.loads(j.read_text())
            L.append(f"\n## usability: {j.name} ({r['frames']} frames of {r['set']}, warm cache)\n")
            cols = ["format", "files", "GB", "alloc GB", "build s", "open+meta s", "frame table s", "seq read s",
                    "random reads s (wrong)", "first image s", "copy python s", "copy robocopy MT8 s",
                    "delete copy s", "delete s"]
            L.append("| " + " | ".join(cols) + " |")
            L.append("|" + "---|" * len(cols))
            for fmt, x in r["formats"].items():
                L.append("| " + " | ".join([fmt, str(x["files"]), f(x["bytes"] / 1e9, 3),
                                            f(x["alloc_bytes_4k_clusters"] / 1e9, 3), f(x["build_s"]),
                                            f(x["open_meta_s"], 3), f(x["frame_table_s"], 3), f(x["seq_read_s"]),
                                            f"{f(x['random_read_s'], 3)} ({x['random_wrong']})", f(x["first_image_s"], 4),
                                            f(x["copy_python_s"]), f(x.get("copy_robocopy_mt8_s")),
                                            f(x["delete_copy_s"]), f(x["delete_s"])]) + " |")
    out = root / "bench_summary.md"
    root.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
