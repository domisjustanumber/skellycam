"""Turn chromium_sync_scrub JSON results into Markdown tables.

  .venv/Scripts/python.exe research/skellycam_recording/recording_upgrade/scripts/chromium_sync_scrub/summarize.py functional
      -> results/chromium_sync_scrub/functional_tables.md   (accuracy / support only, no timing)
  .venv/Scripts/python.exe research/skellycam_recording/recording_upgrade/scripts/chromium_sync_scrub/summarize.py bench
      -> results/chromium_sync_scrub/bench/bench_tables.md  (latency, sync spread, scrub rate, CPU/memory)
  ... summarize.py bench intra
      -> results/intra_playback/bench/bench_tables.md  (bench_intra_seek / bench_intra_sync / bench_intra_scrub; added 2026-11-09)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[5]
RES = REPO / "research/skellycam_recording/recording_upgrade/results/chromium_sync_scrub"


def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def fmt(x, nd=1):
    if x is None:
        return "-"
    if isinstance(x, float):
        return f"{x:.{nd}f}"
    return str(x)


def functional() -> None:
    L = ["# chromium_sync_scrub functional tables (generated by summarize.py functional)", ""]
    vers = [v for v in ("35", "45") if (RES / "functional" / f"e{v}").exists()]
    for v in vers:
        d = load(RES / "functional" / f"e{v}" / "caps.json")
        if d:
            L.append(f"- e{v}: Electron {d['versions']['electron']}, Chromium {d['versions']['chrome']}, finished {d['finished_utc']}")
    L.append("")
    # caps
    caps = {v: load(RES / "functional" / f"e{v}" / "caps.json") for v in vers}
    if caps and all(caps.values()):
        L += ["## Codec support (canPlayType / VideoDecoder.isConfigSupported prefer-hardware 1080p30 / prefer-software / mediaCapabilities 1080p30)", "",
              "| container | codec | " + " | ".join(f"e{v}" for v in vers) + " |", "|---|---|" + "---|" * len(vers)]
        rows = {}
        for v in vers:
            for c in caps[v]["result"]["codecs"]:
                rows.setdefault((c["container"], c["codec"]), {})[v] = (
                    f"{c['canPlayType'] or 'no'} / hw:{c['wc_1080p30_prefer-hardware']} / sw:{c['wc_1080p30_prefer-software']} / {c['mc_1080p30']}")
        for (cont, codec), r in rows.items():
            L.append(f"| {cont} | {codec} | " + " | ".join(r.get(v, "-") for v in vers) + " |")
        L.append("")
        L += ["ImageDecoder.isTypeSupported: " + "; ".join(f"e{v}: " + ", ".join(f"{k.split('/')[1]}={x}" for k, x in caps[v]["result"]["images"].items()) for v in vers), ""]
        L += ["APIs: " + "; ".join(f"e{v}: " + ", ".join(f"{k}={x}" for k, x in caps[v]["result"]["api"].items()) for v in vers), ""]
    # seek
    for name, title in (("seek_batch", "Random seeks (exact = burned-in index read back == requested frame)"),
                        ("step_batch", "Single-frame steps (M forward then 2M back from random starts)")):
        res = {}
        for v in vers:
            merged = []
            for f in sorted((RES / "functional" / f"e{v}").glob(f"{name}*.json")):
                merged += (load(f) or {}).get("result", [])
            res[v] = {"result": merged} if merged else None
        if not any(res.values()):
            continue
        L += [f"## {title}", "",
              "| clip | path | mode | " + " | ".join(f"e{v} exact/n" for v in vers) + " | " + " | ".join(f"e{v} wrong (offset:count)" for v in vers)
              + (" | " + " | ".join(f"e{v} fwd / back exact" for v in vers) if name == "step_batch" else "") + " | notes |",
              "|---|---|---|" + "---|" * (len(vers) * (3 if name == "step_batch" else 2)) + "---|"]
        keyed = {}
        for v in vers:
            for x in (res[v] or {}).get("result", []):
                c = x["config"]
                keyed.setdefault((c["clip"], c["path"], c.get("mode", "-") if c["path"] == "video" else "-"), {})[v] = x["result"]
        for (clip, path, mode), r in keyed.items():
            cells, wrong, steps, notes = [], [], [], set()
            for v in vers:
                s = r.get(v, {})
                s = s.get("summary", s)
                if "error" in s:
                    cells.append("ERR"); wrong.append(s["error"][:60]); steps.append("-"); continue
                cells.append(f"{s.get('exact')}/{s.get('n')}")
                wrong.append(", ".join(f"{k}:{n}" for k, n in s.get("off_by_hist", {}).items()) + (f" unreadable:{s['unreadable']}" if s.get("unreadable") else "") or "0")
                steps.append(f"{s.get('fwd_exact')}/{s.get('fwd_n')} / {s.get('back_exact')}/{s.get('back_n')}")
                if path == "video":
                    if s.get("rvfc_fired") != s.get("n"):
                        notes.add(f"e{v} rVFC fired {s.get('rvfc_fired')}/{s.get('n')}")
                    if s.get("mediatime_idx_equals_pattern") != s.get("n"):
                        notes.add(f"e{v} mediaTime->index == pattern {s.get('mediatime_idx_equals_pattern')}/{s.get('n')}")
                else:
                    if s.get("flushes"):
                        notes.add(f"e{v} flush fallbacks {s['flushes']}")
                    if s.get("decoder_error"):
                        notes.add(f"e{v} decoder error {s['decoder_error']}")
            L.append(f"| {clip} | {path} | {mode} | " + " | ".join(cells) + " | " + " | ".join(wrong)
                     + (" | " + " | ".join(steps) if name == "step_batch" else "") + f" | {'; '.join(sorted(notes))} |")
        L.append("")
    # jpeg compat
    for v in vers:
        d = load(RES / "functional" / f"e{v}" / "jpegcompat.json")
        if not d:
            continue
        L += [f"## Camera JPEG bytes decoded in Chromium (e{v})", "", "| set | frames | createImageBitmap ok | ImageDecoder ok | ImageDecoder format | errors |", "|---|---|---|---|---|---|"]
        for k, r in d["result"].items():
            L.append(f"| {k} | {r['frames_tested']} | {r['bitmap_ok']} | {r['imagedecoder_ok']} | {r.get('imagedecoder_format')} | {len(r['errors'])} |")
        L.append("")
    jc = load(RES / "functional" / "jpeg_decode_compare.json")
    if jc:
        L += ["## Pixel comparison, frame 0 of each camera set (max abs diff / % exact, RGB)", "",
              "| set | OpenCV vs PyAV | " + " | ".join(f"{k}" for k in sorted({kk for s in jc['sets'].values() for kk in s if kk != 'opencv_vs_pyav'})) + " |"]
        keys = sorted({kk for s in jc["sets"].values() for kk in s if kk != "opencv_vs_pyav"})
        L.append("|---|---|" + "---|" * len(keys))
        for name, s in jc["sets"].items():
            o = s["opencv_vs_pyav"]
            cells = []
            for k in keys:
                r = s.get(k)
                cells.append("-" if not r else ("ERR" if "error" in r else f"vs OpenCV {r['vs_opencv']['max_abs']} / {r['vs_opencv']['pct_exact']}%"))
            L.append(f"| {name} | {o['max_abs']} / {o['pct_exact']}% | " + " | ".join(cells) + " |")
        L.append("")
    for v in vers:
        d = load(RES / "functional" / f"e{v}" / "mp4box.json")
        if not d:
            continue
        L += [f"## mp4box.js {d['result'].get('mp4box_version')} sample table vs recorder index (e{v})", "", "| clip | fragmented | codec string equal | samples | offset / size / pts / sync match |", "|---|---|---|---|---|"]
        for k, r in d["result"]["clips"].items():
            L.append(f"| {k} | {r.get('fragmented')} | {r.get('codec_string_equal')} | {r.get('samples')}/{r.get('manifest_frames')} | {r.get('offset_match')} / {r.get('size_match')} / {r.get('pts_match')} / {r.get('sync_match')} |" if "error" not in r else f"| {k} | ERR {r['error']} | | | |")
        L.append("")
    for v in vers:
        d = load(RES / "functional" / f"e{v}" / "sync_scrub_smoke.json")
        if not d:
            continue
        L += [f"## Sync / scrub harness smoke (e{v}) - functional only, no timing", "", "| test | clip | path | N | ran | errors | pattern mismatches (rVFC mediaTime or drawn index vs burned-in index) |", "|---|---|---|---|---|---|---|"]
        for x in d["result"]:
            c, r = x["config"], x["result"]
            ps = r.get("per_stream", [])
            pm = sum((p.get("pattern_mismatch") or 0) for p in ps) if ps and "pattern_mismatch" in ps[0] else "-"
            errs = sum((p.get("errors") or 0) for p in ps) if ps else "-"
            L.append(f"| {c['test']} | {c['clip']} | {c['path']} | {c['n']} | {'no: ' + r['error'] if 'error' in r else 'yes'} | {errs} | {pm} |")
        L.append("")
    (RES / "functional_tables.md").write_text("\n".join(L), encoding="utf-8")
    print(RES / "functional_tables.md")


def bench(which: str = "") -> None:
    global RES
    if which == "intra":
        RES = REPO / "research/skellycam_recording/recording_upgrade/results/intra_playback"
    L = [f"# {RES.name} bench tables (generated by chromium_sync_scrub/summarize.py bench {which})", "",
         "Timing from performance.now() in the page; CPU = app.getAppMetrics() cumulativeCPUUsage delta / window (cores); memory = working set.", ""]
    for vdir in sorted((RES / "bench").glob("e*")):
        for sdir in sorted(vdir.glob("bench_*")):
            if sdir.name.endswith("_smoke"):
                continue
            files = sorted(p for p in sdir.glob("*.json") if not p.name.startswith("_"))
            if not files:
                continue
            first = load(files[0])
            L += [f"## {vdir.name} {sdir.name} (Electron {first['versions']['electron']} / Chromium {first['versions']['chrome']})", ""]
            kind = sdir.name.replace("bench_intra_", "bench_")
            if kind in ("bench_seek", "bench_step"):
                L += ["| config | exact/n | latency p50 / p95 / max ms | fwd p50 / p95 ms | back p50 / p95 ms | nvidia-smi before -> after |", "|---|---|---|---|---|---|"]
                for f in files:
                    d = load(f); s = d["result"].get("summary", d["result"])
                    lat = s.get("lat_rvfc_ms") or s.get("lat_ms") or {}
                    fw, bk = s.get("lat_fwd_ms") or {}, s.get("lat_back_ms") or {}
                    L.append(f"| {f.stem} | {s.get('exact')}/{s.get('n')} | {fmt(lat.get('p50'))} / {fmt(lat.get('p95'))} / {fmt(lat.get('max'))} | {fmt(fw.get('p50'))} / {fmt(fw.get('p95'))} | {fmt(bk.get('p50'))} / {fmt(bk.get('p95'))} | {d['nvidia_smi']['before']} -> {d['nvidia_smi']['after']} |")
            elif kind == "bench_sync":
                L += ["| config | spread p50 / p95 / max (frames) | spread==0 % | lag max p95 | frames/s per stream (min) | dropped (sum) | follower corrections | CPU cores total / GPU proc | WS MB total | nvidia-smi after |", "|---|---|---|---|---|---|---|---|---|---|"]
                for f in files:
                    d = load(f); r = d["result"]; m = d.get("metrics_summary") or {}
                    sp = r.get("spread") or {}
                    lag = (r.get("lag_max") or {}).get("p95")
                    fps = min(r.get("rvfc_or_draws_per_s") or [0])
                    dropped = sum(x["dropped"] for x in r.get("dropped", [])) if r.get("dropped") else "-"
                    L.append(f"| {f.stem} | {fmt(sp.get('p50'))} / {fmt(sp.get('p95'))} / {fmt(sp.get('max'))} | {fmt(r.get('spread_exact0_pct'))} | {fmt(lag)} | {fmt(fps)} | {dropped} | {r.get('follower_corrections', '-')} | {fmt(m.get('cpu_cores_total_from_cumulative'), 2)} / {fmt((m.get('GPU') or {}).get('cpu_cores_from_cumulative'), 2)} | {fmt(m.get('total_ws_mb_last'), 0)} | {d['nvidia_smi']['after']} |")
            elif kind == "bench_scrub":
                L += ["| config | frames shown/s (min stream) | distinct/s (min) | lag p50 / p95 (frames) | CPU cores total | nvidia-smi after |", "|---|---|---|---|---|---|"]
                for f in files:
                    d = load(f); r = d["result"]; m = d.get("metrics_summary") or {}
                    lg = r.get("lag_frames") or {}
                    L.append(f"| {f.stem} | {fmt(min(r.get('frames_shown_per_s') or [0]))} | {fmt(min(r.get('distinct_per_s') or [0]))} | {fmt(lg.get('p50'))} / {fmt(lg.get('p95'))} | {fmt(m.get('cpu_cores_total_from_cumulative'), 2)} | {d['nvidia_smi']['after']} |")
            L.append("")
    out = RES / "bench" / "bench_tables.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8")
    print(out)


if __name__ == "__main__":
    if sys.argv[1] == "bench":
        bench(sys.argv[2] if len(sys.argv) > 2 else "")
    else:
        functional()
