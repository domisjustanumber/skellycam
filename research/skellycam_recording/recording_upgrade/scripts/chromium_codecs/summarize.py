"""Turn the raw browser-test JSON (results/chromium_codecs/raw/*.json) into Markdown tables.

Writes results/chromium_codecs/tables.md (generated - do not edit by hand).
Run: .venv/Scripts/python.exe research/skellycam_recording/recording_upgrade/scripts/chromium_codecs/summarize.py
"""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[5]
RES = REPO / "research/skellycam_recording/recording_upgrade/results/chromium_codecs"
RAW = RES / "raw"
MEDIA = Path("C:/Users/Dom/Documents/skellycam-raw/skellycam_recording/recording_upgrade_20261109/chromium_codecs")
BROWSERS = [("electron35", "E35"), ("electron45", "E45"), ("chrome156", "C156")]
CONTAINERS = ["mp4", "fmp4", "webm", "mkv", "mov", "avi", "ogg"]


def load(tag: str, suite: str) -> dict | None:
    p = RAW / f"{tag}_{suite}.json"
    if not p.exists():  # the 2026-11-09 Chrome 156 main run writes into raw/chrome156/
        p = RAW / tag / f"{tag}_{suite}.json"
    return json.loads(p.read_text()) if p.exists() else None


def by_suffix(results: dict, kind: str) -> dict:
    """Map 'play|<clip>' etc. (label prefix stripped) -> result."""
    out = {}
    for k, v in results.items():
        parts = k.split("|")
        # label|mode|kind|...  (label may be e.g. electron35.7.5, mode e.g. http-range)
        if len(parts) >= 3 and parts[2] == kind:
            out["|".join(parts[3:])] = v
    return out


def decoder(r: dict) -> str:
    names = []
    for pl in (r.get("media") or {}).values():
        n = pl["props"].get("kVideoDecoderName")
        if n:
            names.append(n)
    return ",".join(sorted(set(names))) or "-"


def play_cell(r: dict | None, mux_ok: bool) -> str:
    if not mux_ok:
        return "n/m"
    if r is None:
        return "?"
    if r.get("timeout"):
        return "TIMEOUT"
    if r.get("ready") != "loadeddata":
        e = r.get("error") or {}
        return f"X{e.get('code', '')}" if e else f"X({r.get('ready')})"
    if r.get("pixelError"):
        return "P(taint)"
    p = r.get("play") or {}
    ok_play = p.get("idxValid", 0) > 0 and p.get("idxValid") == p.get("idxEqExpected") and p.get("monotonic")
    s = f"{r.get('seekExact', 0)}/{r.get('seekTotal', 0)}"
    mad = p.get("madMax")
    # "!" = some presented frame index != round(mediaTime*fps); "!!" = the mismatch is systematic (>2 frames affected)
    bad = p.get("idxValid", 0) - p.get("idxEqExpected", 0)
    flag = "" if ok_play else ("!!" if bad > 2 else "!")
    deltas = sorted({sk["idx"] - sk["k"] for sk in r.get("seeks", []) if sk.get("idx") is not None and sk["idx"] >= 0 and sk["idx"] != sk["k"]})
    d = f" d{deltas}" if deltas else ""
    return f"P{flag} {s}{d} m{mad}" if mad is not None else f"P{flag} {s}{d}"


def main() -> None:
    man = json.loads((MEDIA / "manifest.json").read_text())
    log = json.loads((RES / "make_clips_log.json").read_text())
    data = {tag: load(tag, "main") for tag, _ in BROWSERS}
    serv = {tag: load(tag, "serving") for tag, _ in BROWSERS}
    # PyAV 19.0.2 cross-check clips (make_pyav19_clips.py): E35 picked them up in its main rerun; E45 and C156 ran them
    # separately with --only pyav19. Merge only their play results.
    extra = {"electron45": RAW / "pyav19" / "electron45_main_pyav19.json", "chrome156": RAW / "chrome156" / "chrome156_main_pyav19.json"}
    for tag, p in extra.items():
        if p.exists() and data.get(tag):
            for k, v in json.loads(p.read_text())["results"].items():
                if "|play|pyav19_" in k:
                    data[tag]["results"][k] = v
    L: list[str] = ["# chromium_codecs - generated tables", "", "Generated by scripts/chromium_codecs/summarize.py from results/chromium_codecs/raw/*.json. Do not edit.", ""]

    # versions
    L += ["## Versions (measured: raw/*_main.json)", "", "| runner | browser version | Chromium | V8 |", "|---|---|---|---|"]
    for tag, short in BROWSERS:
        d = data[tag]
        if not d:
            L.append(f"| {short} | NOT RUN | | |"); continue
        if d["runner"] == "electron":
            v = d["versions"]; L.append(f"| {short} | Electron {v['electron']} | {v['chrome']} | {v['v8']} |")
        else:
            v = d["version"]; L.append(f"| {short} | {v['Browser']} | {v['Browser'].split('/')[1]} | {v.get('V8-Version')} |")
    L.append("")

    # play matrix
    L += ["## <video src> play + seek matrix (HTTP with Range; measured)", "",
          "Cell = E35 ; E45 ; C156. `P a/b mM` = loadeddata, every presented frame during ~1.2 s of playback carried the expected index "
          "(`P!` = at least one presented frame did not), `a/b` paused seeks that landed on the exact frame, `mM` = max per-frame content MAD "
          "(luma levels, 0-255) vs source. `Xn` = MediaError code n. `n/m` = ffmpeg 9.0.2 could not mux this pair.", "",
          "| codec | " + " | ".join(CONTAINERS) + " |", "|---|" + "---|" * len(CONTAINERS)]
    plays = {tag: by_suffix(data[tag]["results"], "play") if data[tag] else {} for tag, _ in BROWSERS}
    codecs = list(log["codecs"].keys())
    for cid in codecs:
        row = [cid]
        for k in CONTAINERS:
            mux_ok = log["codecs"][cid]["containers"].get(k, {}).get("ok", False)
            cells = [play_cell(plays[tag].get(f"{cid}__{k}"), mux_ok) for tag, _ in BROWSERS]
            row.append(" ; ".join(cells) if mux_ok else "n/m")
        L.append("| " + " | ".join(row) + " |")
    # camera-native MJPEG
    for c in man.get("camera_clips", []):
        row = [f"{c['id']} (camera bytes, no pattern)"]
        cells = []
        for tag, _ in BROWSERS:
            r = plays[tag].get(c["id"])
            cells.append("?" if r is None else ("loaded" if r.get("ready") == "loadeddata" else f"X{(r.get('error') or {}).get('code', '')}"))
        L.append(f"| {row[0]} | container={c['container']} | " + " ; ".join(cells) + " | | | | | |")
    L.append("")

    # errors detail
    L += ["### MediaError messages (first per codec/container/browser)", "", "| clip | browser | code | message |", "|---|---|---|---|"]
    for cid in codecs:
        for k in CONTAINERS:
            for tag, short in BROWSERS:
                r = plays[tag].get(f"{cid}__{k}")
                if r and r.get("error"):
                    L.append(f"| {cid}__{k} | {short} | {r['error']['code']} | {r['error']['message'][:140].replace('|', '/')} |")
    for c in man.get("camera_clips", []):
        for tag, short in BROWSERS:
            r = plays[tag].get(c["id"])
            if r and r.get("error"):
                L.append(f"| {c['id']} | {short} | {r['error']['code']} | {r['error']['message'][:140].replace('|', '/')} |")
    L.append("")

    # PyAV 19.0.2 clips
    py = [c for c in man["clips"] if c["id"].startswith("pyav19_")]
    if py:
        L += ["### Same play + seek test, clips encoded and muxed with PyAV 19.0.2 (make_pyav19_clips.py; measured)", "",
              "Cell = E35 ; E45 ; C156 play cell + decoder (kVideoDecoderName).", "", "| clip | result |", "|---|---|"]
        for c in py:
            cells = []
            for tag, _ in BROWSERS:
                r = plays[tag].get(c["id"])
                cells.append("?" if r is None else f"{play_cell(r, True)} {decoder(r)}")
            L.append(f"| {c['id']} | " + " ; ".join(cells) + " |")
        L.append("")

    # decoder names
    L += ["## Decoder chosen by the <video> pipeline (measured: DevTools Media domain kVideoDecoderName / kIsPlatformVideoDecoder)", "",
          "| codec | E35 | E45 | C156 |", "|---|---|---|---|"]
    for cid in codecs:
        cells = []
        for tag, _ in BROWSERS:
            names = set()
            for k in CONTAINERS:
                r = plays[tag].get(f"{cid}__{k}")
                if r and r.get("ready") == "loadeddata":
                    names.add(decoder(r))
            cells.append(",".join(sorted(names)) or "-")
        L.append(f"| {cid} | " + " | ".join(cells) + " |")
    L.append("")

    # MSE
    L += ["## MSE (whole file appended to one SourceBuffer; measured)", "", "Cell = E35 ; E45 ; C156, same notation as the play matrix.", "",
          "| clip | mime | result |", "|---|---|---|"]
    mses = {tag: by_suffix(data[tag]["results"], "mse") if data[tag] else {} for tag, _ in BROWSERS}
    keys = sorted({k for m in mses.values() for k in m})
    for k in keys:
        mime = next((m[k].get("mime") for m in mses.values() if k in m), "")
        cells = []
        for tag, _ in BROWSERS:
            r = mses[tag].get(k)
            if r and r.get("setupError"):
                cells.append("X(" + r["setupError"][:60] + ")")
            else:
                cells.append(play_cell(r, True))
        L.append(f"| {k} | `{mime}` | " + " ; ".join(cells) + " |")
    L.append("")

    # WebCodecs decode
    L += ["## WebCodecs VideoDecoder actual decode of the elementary streams (measured)", "",
          "Cell = isConfigSupported / outputs / outputs whose index == output position / max MAD. E35 ; E45 ; C156.", "",
          "| codec | codec string | prefer-hardware | prefer-software |", "|---|---|---|---|"]
    wcs = {tag: by_suffix(data[tag]["results"], "wc") if data[tag] else {} for tag, _ in BROWSERS}
    for cid in codecs:
        cells = {}
        cs = ""
        for hw in ["prefer-hardware", "prefer-software"]:
            parts = []
            for tag, _ in BROWSERS:
                r = wcs[tag].get(f"{cid}|{hw}")
                if not r:
                    parts.append("-"); continue
                cs = r.get("codec", cs)
                if r.get("fatal"):
                    parts.append("FATAL " + r["fatal"][:40]); continue
                e = (r.get("errors") or [""])[0][:50]
                parts.append(f"{'T' if r.get('isConfigSupported') else 'F'}/{r.get('outputs')}/{r.get('inOrderCorrect')}/{r.get('madMax')}" + (f" ({e})" if e else ""))
            cells[hw] = " ; ".join(parts)
        if any(v.strip(" ;-") for v in cells.values()):
            L.append(f"| {cid} | `{cs}` | {cells['prefer-hardware']} | {cells['prefer-software']} |")
    L.append("")

    # Probe tables
    probes = {tag: next((v for k, v in data[tag]["results"].items() if k.endswith("|probe")), None) if data[tag] else None for tag, _ in BROWSERS}
    L += ["## API probes (measured)", "", "### canPlayType / MSE isTypeSupported / MediaCapabilities(file) supported,smooth,powerEfficient", "",
          "Cell = E35 ; E45 ; C156. canPlayType: `pr`=probably `my`=maybe `-`=\"\". MSE: T/F. MC: s=supported, m=smooth, e=powerEfficient (`---` none).", "",
          "| codec / mime | canPlayType | MSE | MC file |", "|---|---|---|---|"]
    def abbr(x):
        return {"probably": "pr", "maybe": "my", "": "-"}.get(x, str(x))
    def mcabbr(m):
        if not m or "err" in m:
            return "err"
        return ("s" if m["supported"] else "-") + ("m" if m["smooth"] else "-") + ("e" if m["powerEfficient"] else "-")
    first = next((p for p in probes.values() if p), None)
    if first:
        for cid, mimes in first["video"].items():
            for mime in mimes:
                cp, ms, mc = [], [], []
                for tag, _ in BROWSERS:
                    p = probes[tag]
                    e = p["video"].get(cid, {}).get(mime) if p else None
                    cp.append(abbr(e["canPlayType"]) if e else "?")
                    ms.append(("T" if e["mse"] else "F") if e else "?")
                    mc.append(mcabbr(e["mcFile"]) if e else "?")
                L.append(f"| {cid} `{mime}` | {' ; '.join(cp)} | {' ; '.join(ms)} | {' ; '.join(mc)} |")
        L.append("")
        L += ["### Bare container MIME (no codecs parameter)", "", "| mime | canPlayType | MSE |", "|---|---|---|"]
        for k in first["containersBare"]:
            cp = [abbr(probes[t]["containersBare"][k]["canPlayType"]) if probes[t] else "?" for t, _ in BROWSERS]
            ms = [("T" if probes[t]["containersBare"][k]["mse"] else "F") if probes[t] else "?" for t, _ in BROWSERS]
            L.append(f"| {k} | {' ; '.join(cp)} | {' ; '.join(ms)} |")
        L.append("")
        L += ["### WebCodecs VideoDecoder.isConfigSupported (1280x720)", "", "Cell = prefer-hardware/prefer-software/no-preference, E35 ; E45 ; C156", "",
              "| codec string | result |", "|---|---|"]
        for k in first["webcodecs"]:
            cells = []
            for tag, _ in BROWSERS:
                p = probes[tag]
                w = p["webcodecs"].get(k) if p else None
                if not w:
                    cells.append("?"); continue
                cells.append("/".join(("T" if w[h].get("supported") else ("F" if "supported" in w[h] else "err")) for h in ["preferHardware", "preferSoftware", "noPreference"]))
            L.append(f"| `{k}` | {' ; '.join(cells)} |")
        L.append("")
        L += ["### ImageDecoder.isTypeSupported", "", "| type | E35 ; E45 ; C156 |", "|---|---|"]
        for t in first["imageDecoder"]:
            L.append(f"| {t} | " + " ; ".join(str(probes[tg]["imageDecoder"][t].get("supported")) if probes[tg] else "?" for tg, _ in BROWSERS) + " |")
        L.append("")
        L += ["### Audio (API probes only - no audio files were played)", "", "| codec / mime | canPlayType | MSE | MC file |", "|---|---|---|---|"]
        for aid, mimes in first["audio"].items():
            for mime in mimes:
                cp = [abbr(probes[t]["audio"][aid][mime]["canPlayType"]) if probes[t] else "?" for t, _ in BROWSERS]
                ms = [("T" if probes[t]["audio"][aid][mime]["mse"] else "F") if probes[t] else "?" for t, _ in BROWSERS]
                mc = [mcabbr(probes[t]["audio"][aid][mime]["mcFile"]) if probes[t] else "?" for t, _ in BROWSERS]
                L.append(f"| {aid} `{mime}` | {' ; '.join(cp)} | {' ; '.join(ms)} | {' ; '.join(mc)} |")
        L += ["", "| AudioDecoder.isConfigSupported (48 kHz stereo) | E35 ; E45 ; C156 |", "|---|---|"]
        for c in first["audioWebCodecs"]:
            L.append(f"| {c} | " + " ; ".join(str(probes[t]["audioWebCodecs"][c].get("supported", probes[t]["audioWebCodecs"][c].get("err"))) if probes[t] else "?" for t, _ in BROWSERS) + " |")
        L += ["", "### Feature presence", "", "| feature | E35 ; E45 ; C156 |", "|---|---|"]
        for f in first["features"]:
            L.append(f"| {f} | " + " ; ".join(str(probes[t]["features"][f]) if probes[t] else "?" for t, _ in BROWSERS) + " |")
        L.append("")

    # images
    imgs = {tag: next((v for k, v in data[tag]["results"].items() if k.endswith("|img")), None) if data[tag] else None for tag, _ in BROWSERS}
    L += ["## Still images: decode + content check (measured)", "",
          "Per group: images decoded OK / total, and max 16x9-grid luma MAD vs expected (OpenCV decode for camera JPEGs). Cell = E35 ; E45 ; C156.", "",
          "| group | ImageDecoder | createImageBitmap | <img> |", "|---|---|---|---|"]
    groups: dict[str, list[str]] = {}
    for im in man["images"]:
        g = im["id"].rsplit("_frame_", 1)[0] if im["id"].startswith("cam_") else im["id"]
        groups.setdefault(g, []).append(im["id"])
    for g, ids in groups.items():
        row = [g]
        for api in ["imageDecoder", "createImageBitmap", "img"]:
            parts = []
            for tag, _ in BROWSERS:
                d = imgs[tag]
                if not d:
                    parts.append("?"); continue
                rs = [d["images"][i].get(api) for i in ids]
                ok = [r for r in rs if r and r.get("ok")]
                mx = max((r["mad"] for r in ok if r.get("mad") is not None), default=None)
                err = next((r.get("err") for r in rs if r and not r.get("ok")), None)
                parts.append(f"{len(ok)}/{len(ids)} m{mx}" + (f" ({err[:40]})" if err else ""))
            row.append(" ; ".join(parts))
        L.append("| " + " | ".join(row) + " |")
    L.append("")

    # software-decode variant
    sw = {tag: load(tag, "swdecode") for tag, _ in BROWSERS}
    if any(sw.values()):
        L += ["## Hardware decode disabled (--disable-accelerated-video-decode; measured, suite=swdecode)", "",
              "Cell = decoder (kVideoDecoderName) + play cell. E35 ; E45 ; C156.", "", "| clip | result |", "|---|---|"]
        swp = {tag: by_suffix(sw[tag]["results"], "play") if sw[tag] else {} for tag, _ in BROWSERS}
        for clip in sorted({k for m in swp.values() for k in m}):
            cells = []
            for tag, _ in BROWSERS:
                r = swp[tag].get(clip)
                cells.append("?" if r is None else f"{decoder(r)} {play_cell(r, True)}")
            L.append(f"| {clip} | " + " ; ".join(cells) + " |")
        L.append("")

    # serving
    L += ["## Serving mode vs seeking (measured; suite=serving)", "",
          "Cell = P exact-seeks/total, R = kIsRangeHeaderSupported and S = kIsStreaming (DevTools Media domain), sk = HTMLMediaElement.seekable at loadeddata. big_* clips are 120 MB (600 frames) and get 15 seek targets incl. frames 150/299/451/598.", ""]
    for tag, short in BROWSERS:
        s = serv[tag]
        if not s:
            L.append(f"{short}: NOT RUN"); continue
        modes = []
        rows: dict[str, dict[str, str]] = {}
        for k, r in s["results"].items():
            parts = k.split("|")
            mode, clip = parts[1], parts[3]
            if mode not in modes:
                modes.append(mode)
            rng = "-"; strm = "-"
            for pl in (r.get("media") or {}).values():
                rng = pl["props"].get("kIsRangeHeaderSupported", rng)
                strm = pl["props"].get("kIsStreaming", strm)
            rng = f"{rng} S={strm}"
            if r.get("ready") == "loadeddata":
                cell = f"P {r.get('seekExact')}/{r.get('seekTotal')} R={rng} sk={r.get('meta', {}).get('seekable')}"
                if r.get("pixelError"):
                    cell = f"P(taint: {r['pixelError'][:30]}) seeks completed {r.get('seekCompleted')} R={rng} sk={r.get('meta', {}).get('seekable')}"
            else:
                cell = f"X {(r.get('error') or {}).get('message', r.get('ready', ''))[:60]}"
            rows.setdefault(clip, {})[mode] = cell
        L += [f"### {short}", "", "| clip | " + " | ".join(modes) + " |", "|---|" + "---|" * len(modes)]
        for clip, cells in rows.items():
            L.append(f"| {clip} | " + " | ".join(cells.get(m, "?") for m in modes) + " |")
        L.append("")
        # request evidence
        if s.get("protocolLog"):
            L += [f"{short} custom-protocol request log summary (media requests only): requests with a Range header / responses 206, per scheme:", ""]
            agg: dict[str, list[int]] = {}
            for e in s["protocolLog"]:
                a = agg.setdefault(e["scheme"], [0, 0, 0])
                a[0] += 1; a[1] += 1 if e.get("range") else 0; a[2] += 1 if e.get("status") == 206 else 0
            L += ["| scheme | requests | with Range header | status 206 |", "|---|---|---|---|"]
            for sc, a in agg.items():
                L.append(f"| {sc} | {a[0]} | {a[1]} | {a[2]} |")
            L.append("")
        if isinstance(s.get("httpRequestLog"), list):
            agg = {}
            for e in s["httpRequestLog"]:
                key = e["path"][:3]
                a = agg.setdefault(key, [0, 0, 0]); a[0] += 1; a[1] += 1 if e.get("range") else 0; a[2] += 1 if e.get("status") == 206 else 0
            L += [f"{short} HTTP request log (media paths): /r/ = Range-capable, /n/ = no Range", "", "| path | requests | with Range header | status 206 |", "|---|---|---|---|"]
            for k2, a in agg.items():
                L.append(f"| {k2} | {a[0]} | {a[1]} | {a[2]} |")
            L.append("")
    (RES / "tables.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote", RES / "tables.md")


if __name__ == "__main__":
    main()
