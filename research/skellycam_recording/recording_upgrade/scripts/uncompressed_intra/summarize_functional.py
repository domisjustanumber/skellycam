"""Turn functional_matrix_pyav*.json into Markdown tables (results/uncompressed_intra/functional_tables.md).

  .venv/Scripts/python.exe research/skellycam_recording/recording_upgrade/scripts/uncompressed_intra/summarize_functional.py
Cell codes (acceptance table):
  N   native pix_fmt, decoded bit-exact          R   exact numpy re-layout/re-tag, source recovered bit-exact
  L   lossy (by design: lossy config, swscale conversion, or encoder dropped bits)
  !   lossless config but NOT bit-exact          -   no exact path (lossless config) / no path
  mux PyAV add_stream refused the container      enc encoder failed to open / encode       dec decode failed
"""
from __future__ import annotations

import json
from pathlib import Path

RES = Path(__file__).resolve().parents[2] / "results" / "uncompressed_intra"
SRC_ORDER = ["yuyv422", "uyvy422", "nv12", "yuv420p", "gray", "gray16le", "p010le", "rgb24", "bgr24",
             "bayer_rggb8", "bayer8_quad", "bayer_rggb16le", "raw12_packed", "raw10_packed", "bayer16_quad"]
RAW_BYTES = {"yuyv422": 4147200, "uyvy422": 4147200, "nv12": 3110400, "yuv420p": 3110400, "gray": 2073600,
             "gray16le": 4147200, "p010le": 6220800, "rgb24": 6220800, "bgr24": 6220800, "bayer_rggb8": 2073600,
             "bayer8_quad": 2073600, "bayer_rggb16le": 4147200, "raw12_packed": 3110400, "raw10_packed": 2592000, "bayer16_quad": 4147200}


def code(r: dict) -> str:
    st = r.get("stage")
    if st == "no_path":
        return "-"
    if st in ("add_stream",) and "does not support" in str(r.get("error")):
        return "mux"
    if st != "done":
        return "enc"
    if r.get("frames_decoded") != r.get("frames_fed") or r.get("decode_error"):
        return "dec"
    exact = r.get("bit_exact_vs_fed")
    if exact and r.get("path") == "native":
        return "N"
    if exact and r.get("bit_exact_vs_source"):
        return "R"
    if r.get("lossless_intended") and r.get("path") != "swscale (lossy)":
        return "!"
    return "L"


def main() -> None:
    out = ["# Functional matrix tables (generated by summarize_functional.py)", "",
           "Source: real YUY2 1080p frames (corpus c930e_1080p_yuy2, 4 frames) and formats derived from them (uintra_frames.py).",
           "Codes: N native+exact, R exact re-layout (source recovered), L lossy, ! lossless config not exact, - no exact path, "
           "mux container refused by PyAV, enc encoder open/encode failed, dec decode failed.", ""]
    data = {}
    for v in ("18.0.0", "19.0.2"):
        p = RES / f"functional_matrix_pyav{v}.json"
        if p.exists():
            data[v] = json.loads(p.read_text())
    for v, d in data.items():
        rs = d["results"]
        cfgs = list(dict.fromkeys(r["config"] for r in rs))
        idx = {(r["source"], r["config"]): r for r in rs}
        out += [f"## Acceptance and exactness, PyAV {v} (FFmpeg {d['meta']['library_versions']['libavcodec']})", "",
                "| config | " + " | ".join(SRC_ORDER) + " |", "|---" * (len(SRC_ORDER) + 1) + "|"]
        for c in cfgs:
            out.append(f"| {c} | " + " | ".join(code(idx[(s, c)]) if (s, c) in idx else "" for s in SRC_ORDER) + " |")
        out.append("")
    if "19.0.2" in data:
        rs = data["19.0.2"]["results"]
        out += ["## Bit-exact lossless results by source, sorted by bytes/frame (PyAV 19.0.2)", "",
                "bytes/frame = mean packet size over the 4 frames; ratio = raw source bytes / bytes per frame. "
                "Sizes depend on the synthetic noise in the low bits of the >8-bit derived sources (see uintra_frames.py).", "",
                "| source | config | path | target pix_fmt | KB/frame | ratio vs raw |", "|---|---|---|---|---|---|"]
        for s in SRC_ORDER:
            ok = [r for r in rs if r["source"] == s and code(r) in ("N", "R") and not r["codec"] == "rawvideo"]
            ok.sort(key=lambda r: r.get("packet_bytes_mean") or 1e18)
            for r in ok:
                b = r.get("packet_bytes_mean")
                out.append(f"| {s} | {r['config']} | {r['path']} | {r['target_pix_fmt']} | {b / 1000:.0f} | {RAW_BYTES[s] / b:.2f} |")
        out += ["", "## Truncation at 50 % of file size (PyAV 19.0.2, yuyv422 / bayer_rggb16le sources)", "",
                "| config | source | frames decoded of 4 | frames bit-exact | error |", "|---|---|---|---|---|"]
        for r in rs:
            if r["source"] in ("yuyv422", "bayer_rggb16le") and r.get("stage") == "done":
                out.append(f"| {r['config']} | {r['source']} | {r.get('trunc50_frames_decoded')} | {r.get('trunc50_frames_exact')} | "
                           f"{(r.get('trunc50_error') or '')[:60]} |")
        out += ["", "## Configs whose packets are NOT all flagged keyframe (PyAV 19.0.2)", ""]
        nk = sorted({(r["config"]) for r in rs if r.get("stage") == "done" and not r.get("all_keyframes")})
        out += [f"- {c}" for c in nk] or ["- none"]
        out += ["", "## Encoder/muxer errors (first source that hit each distinct error, PyAV 19.0.2)", "",
                "| config | source | stage | error | libav log |", "|---|---|---|---|---|"]
        seen = set()
        for r in rs:
            if r.get("stage") not in ("done", "no_path"):
                k = (r["config"], (r.get("libav_log") or [r.get("error")])[0])
                if k in seen:
                    continue
                seen.add(k)
                log = "; ".join(r.get("libav_log") or [])
                out.append(f"| {r['config']} | {r['source']} | {r['stage']} | {str(r.get('error'))[:90]} | {log[:120]} |")
        out += ["", "## Lossless configs that decoded but were not bit-exact (PyAV 19.0.2)", "",
                "| config | source | fed pix_fmt | decoded pix_fmt | codec_tag |", "|---|---|---|---|---|"]
        for r in rs:
            if code(r) == "!":
                out.append(f"| {r['config']} | {r['source']} | {r['target_pix_fmt']} | {r.get('decoded_pix_fmt')} | {r.get('codec_tag')} |")
    if "18.0.0" in data and "19.0.2" in data:
        a = {(r["source"], r["config"]): r for r in data["18.0.0"]["results"]}
        b = {(r["source"], r["config"]): r for r in data["19.0.2"]["results"]}
        out += ["", "## Differences PyAV 18.0.0 -> 19.0.2", "", "| source | config | 18.0.0 | 19.0.2 | note |", "|---|---|---|---|---|"]
        for k in a:
            if k in b and (code(a[k]), a[k].get("path")) != (code(b[k]), b[k].get("path")):
                note = f"18 decoded {a[k].get('decoded_pix_fmt')}; 19 path {b[k].get('path')} {(b[k].get('libav_log') or [''])[0]}"
                out.append(f"| {k[0]} | {k[1]} | {code(a[k])} | {code(b[k])} | {note[:110]} |")
    (RES / "functional_tables.md").write_text("\n".join(out) + "\n")
    print("wrote", RES / "functional_tables.md")


if __name__ == "__main__":
    main()
