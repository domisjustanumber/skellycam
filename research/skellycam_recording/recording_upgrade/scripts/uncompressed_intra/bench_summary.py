"""Aggregate results/uncompressed_intra/bench/*.json into bench/bench_summary.md (one table per bench type).

  .venv/Scripts/python.exe research/skellycam_recording/recording_upgrade/scripts/uncompressed_intra/bench_summary.py
"""
from __future__ import annotations

import json
from pathlib import Path

BENCH = Path(__file__).resolve().parents[2] / "results" / "uncompressed_intra" / "bench"


def main() -> None:
    rows, still, deb = [], [], []
    for p in sorted(BENCH.glob("*.json")):
        d = json.loads(p.read_text())
        if "encode_fps" in d:
            rows.append(d)
        elif d.get("bench") == "py_still":
            still.append(d)
        elif d.get("bench") == "debayer":
            deb.append(d)
    out = ["# uncompressed_intra bench summary (generated by bench_summary.py)", "",
           "cpu/stream = process CPU seconds per second of 30 fps video (1.0 = one core). Frames are looped real frames.", ""]
    def mm(d, k, fmt="{:.0f}"):
        st = (d.get("stats") or {}).get(k)
        if not st:
            v = d.get(k)
            return "" if v is None else str(v)
        return f"{fmt.format(st['median'])} ({fmt.format(st['min'])}-{fmt.format(st['max'])})"

    if rows:
        out += ["Values: median (min-max) over the timed repetitions; the warm-up run is discarded. "
                "sys CPU% = whole-machine CPU before the case / median during encode (other agents were running).", "",
                "| config | source | res | threads | PyAV | reps x frames | enc fps | cpu/stream | p99 ms | KB/frame | dec fps | prep ms | sys CPU% before / during |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for d in sorted(rows, key=lambda d: (d["res"], d["source"], d["config"], d["threads"], d["av_version"])):
            during = (d.get("stats") or {}).get("system_cpu_percent_during_encode") or {}
            out.append(f"| {d['config']} | {d['source']} | {d['res']} | {d['threads']} | {d['av_version']} | {d.get('reps', 1)}x{d['frames']} | "
                       f"{mm(d, 'encode_fps')} | {mm(d, 'encode_cpu_cores_per_30fps_stream', '{:.2f}')} | {d['encode_latency_ms']['p99']} | "
                       f"{d['bytes_per_frame'] / 1000:.0f} | {mm(d, 'decode_fps')} | {d['prep_ms_per_frame']} | "
                       f"{d.get('system_cpu_percent_before', d.get('system_cpu_percent_1s_before'))} / {during.get('median', '')} |")
    for d in still:
        out += ["", f"## Python still-image encoders ({d.get('versions')})", "",
                "| case | workers | enc fps median (min-max) | cpu/stream median (min-max) | KB/frame | dec fps | error |", "|---|---|---|---|---|---|---|"]
        for r in d["results"]:
            out.append(f"| {r['case']} | {r['workers']} | {r.get('encode_fps')} ({r.get('encode_fps_min')}-{r.get('encode_fps_max')}) | "
                       f"{r.get('cpu_cores_per_30fps_stream')} ({r.get('cpu_cores_min')}-{r.get('cpu_cores_max')}) | "
                       f"{(r.get('bytes_per_frame') or 0) / 1000:.0f} | {r.get('decode_fps', '')} | {r.get('error', '')} |")
    for d in deb:
        out += ["", f"## Debayer cost ({d.get('versions')})", "", "| method | bits | ms/frame median (min-max) | error |", "|---|---|---|---|"]
        for r in d["results"]:
            out.append(f"| {r['method']} | {r['bits']} | {r.get('ms_per_frame')} ({r.get('ms_min')}-{r.get('ms_max')}) | {r.get('error', '')} |")
    (BENCH / "bench_summary.md").write_text("\n".join(out) + "\n")
    print("wrote", BENCH / "bench_summary.md")


if __name__ == "__main__":
    main()
