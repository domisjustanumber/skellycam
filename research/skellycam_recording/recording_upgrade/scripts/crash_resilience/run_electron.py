"""Electron <video> playback of clean, killed, truncated and repaired recordings (formats Chromium can play at all).

Inputs come from run_kill_matrix.py outputs (kill_matrix_a.json / kill_matrix_b.json and MEDIA/kill/).
Truncated copies (30 / 60 / 95 % of the drained:N image) are written to MEDIA/electron_trunc/.
The probe app is electron_probe/ (hidden BrowserWindow; ELECTRON_RUN_AS_NODE is removed from the env because the
VS Code host sets it). Frames are judged by getVideoPlaybackQuality().totalVideoFrames during a playbackRate-4 play
from 0 (decoded_during_play) and the final currentTime; rVFC callbacks are recorded but do not fire reliably in a
hidden window.

usage: python run_electron.py --electron <path to electron.exe> --label e35
writes results/crash_resilience/electron_<label>.json and .md
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common_cr as cc  # noqa: E402

E35 = "C:/Users/Dom/GitHub/freemocap/skellycam/skellycam-ui/node_modules/electron/dist/electron.exe"
TRUNC_CONT = ["mkv+fp", "mkv_cl0+fp", "webm+fp", "webm_cl0+fp", "fmp4_kf+fp", "fmp4_every+fp", "fmp4_1s+fp", "mp4+fp"]


def build_list(n: int) -> list[dict]:
    runs = []
    for t in ("kill_matrix_a", "kill_matrix_b"):
        f = cc.RES / f"{t}.json"
        if f.exists():
            runs += json.loads(f.read_text())["runs"]
    items = []
    for r in runs:
        if "summary" not in r:
            continue
        kind = cc.spec(r["container"])[3]
        if kind != "file":
            continue
        p = Path(r["path"])
        if not p.exists() or p.stat().st_size == 0:
            continue
        if r["payload"] in ("mjpeg", "ffv1") and not (r["mode"] == "clean" and r["container"] in ("mkv", "mp4", "fmp4_kf", "avi", "nut")):
            continue
        if r["mode"] not in ("clean", f"drained:{n}", "rt"):
            continue  # idle:1 / idle:N are mostly empty files; busy is like rt
        items.append({"path": str(p).replace("\\", "/"), "id": p.stem, "payload": r["payload"], "container": r["container"],
                      "case": r["mode"], "expected_frames": r["summary"]["ffprobe"], "timeout_ms": 8000})
        if r["payload"] in ("av1", "h264nv") and r["mode"] in (f"drained:{n}", "rt"):
            rp = cc.MEDIA / "kill/repaired" / (p.stem + ".repaired.mkv")
            if rp.exists() and rp.stat().st_size:
                items.append({"path": str(rp).replace("\\", "/"), "id": rp.stem, "payload": r["payload"],
                              "container": r["container"], "case": r["mode"] + " -> ffmpeg -c copy .mkv",
                              "expected_frames": cc.ffprobe_count(str(rp))["frames"], "timeout_ms": 8000})
    # truncations
    td = cc.MEDIA / "electron_trunc"
    td.mkdir(parents=True, exist_ok=True)
    for p in ("av1", "h264nv"):
        for c in TRUNC_CONT:
            img = cc.out_path(cc.MEDIA / "kill", p, c, f"drained{n}")
            if not img.exists() or img.stat().st_size == 0:
                continue
            data = img.read_bytes()
            for frac in (0.3, 0.6, 0.95):
                dst = td / f"{img.stem}__trunc{int(frac * 100)}{img.suffix}"
                dst.write_bytes(data[: int(len(data) * frac)])
                items.append({"path": str(dst).replace("\\", "/"), "id": dst.stem, "payload": p, "container": c,
                              "case": f"truncated {int(frac * 100)}%", "expected_frames": cc.ffprobe_count(str(dst))["frames"],
                              "timeout_ms": 8000})
    return items


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--electron", default=E35)
    ap.add_argument("--label", default="e35")
    ap.add_argument("--n", type=int, default=150)
    ap.add_argument("--list", default=None, help="reuse an existing list json")
    a = ap.parse_args()
    lst = Path(a.list) if a.list else cc.TEMP / "electron_list.json"
    if not a.list:
        items = build_list(a.n)
        lst.write_text(json.dumps(items, indent=1))
    out = cc.RES / f"electron_{a.label}.json"
    env = {k: v for k, v in os.environ.items() if k != "ELECTRON_RUN_AS_NODE"}
    subprocess.run([a.electron, str(cc.SCRIPTS / "electron_probe"), str(lst), str(out)], env=env, timeout=7200,
                   capture_output=True)
    res = json.loads(out.read_text())
    write_md(res, cc.RES / f"electron_{a.label}.md")


def write_md(res, path):
    v = res["versions"]
    L = [f"# Electron <video> playback of damaged recordings (generated by run_electron.py)", "",
         f"Electron {v['electron']} / Chromium {v['chrome']}; hidden window. expected = ffprobe -count_frames on the same "
         "file; decoded = totalVideoFrames decoded while playing from 0 at rate 4; end t = currentTime when 'ended' fired "
         "(or at the 8 s timeout); metadata/seek/play() waits time out after 5 s; seek = 'seeked' fired for a seek to duration/2 (or 1 s when duration is Infinity).", "",
         "| payload | container | case | expected | metadata | duration | seek | ended | end t | decoded | error |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in res["results"]:
        err = r.get("error") or r.get("error_after_play") or r.get("probe_exception") or ""
        if isinstance(err, dict):
            err = f"{err.get('code')}: {err.get('message', '')[:70]}"
        L.append(f"| {r['payload']} | {r['container']} | {r['case']} | {r['expected_frames']} | {r.get('loadedmetadata')} | "
                 f"{r.get('duration', '')} | {r.get('seek_mid', '')} | {r.get('ended', '')} | {r.get('final_currentTime', '')} | "
                 f"{r.get('decoded_during_play', '')} | {err} |")
    path.write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
