"""Tables for intra_playback from the functional JSONs (no timing fields exist in them).

Reads  results/intra_playback/functional/<e35|e45|c156>/{caps,seek_*,step_*,play_*,jpegmkv_*,sync4}.json
       results/intra_playback/clips_summary.json
Writes results/intra_playback/functional_tables.md
Run:   uv run --script research/skellycam_recording/recording_upgrade/scripts/intra_playback/summarize_intra.py
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[5]
R = REPO / "research/skellycam_recording/recording_upgrade/results/intra_playback"
BROWSERS = ["e35", "e45", "c156"]


def load(b: str, prefix: str) -> list[dict]:
    out = []
    for f in sorted((R / "functional" / b).glob(f"{prefix}*.json")):
        if f.name.endswith("_smoke.json"):
            continue
        d = json.loads(f.read_text())
        res = d.get("result")
        if isinstance(res, list):
            for x in res:
                out.append({"file": f.name, **x})
        else:
            out.append({"file": f.name, "config": d.get("params", {}), "result": res, "versions": d.get("versions")})
    return out


def versions() -> dict:
    v = {}
    for b in BROWSERS:
        f = R / "functional" / b / "caps.json"
        if f.exists():
            d = json.loads(f.read_text())
            v[b] = d.get("versions")
    return v


def dec_names(r: dict) -> str:
    m = r.get("media") if isinstance(r, dict) else None
    if not isinstance(m, dict):
        return ""
    names = sorted({f"{p.get('kVideoDecoderName', '?')}" for p in m.get("players", []) if p.get("kVideoDecoderName")})
    errs = sorted({e for p in m.get("players", []) for e in p.get("errors", [])})
    return ",".join(names) + (f" ERR {';'.join(errs)}" if errs else "")


def cell_seek(r: dict) -> str:
    if not isinstance(r, dict):
        return "?"
    if "error" in r and "summary" not in r:
        return "X: " + r["error"][:70].replace("|", "/")
    s = r["summary"]
    t = f"{s['exact']}/{s['n']}"
    if s.get("unreadable"):
        t += f" u{s['unreadable']}"
    if s.get("off_by_hist"):
        t += f" off{json.dumps(s['off_by_hist']).replace(' ', '')}"
    if "fwd_exact" in s:
        t += f" (f{s['fwd_exact']}/{s['fwd_n']} b{s['back_exact']}/{s['back_n']})"
    if s.get("flushes"):
        t += f" fl{s['flushes']}"
    if s.get("decoded_hist") and set(s["decoded_hist"]) != {"1"}:
        t += f" dec{json.dumps(s['decoded_hist']).replace(' ', '')}"
    if s.get("errors"):
        t += f" err{s['errors']}"
    if "rvfc_fired" in s and s["rvfc_fired"] != s["n"]:
        t += f" rvfc{s['rvfc_fired']}"
    return t


def main() -> None:
    cs = json.loads((R / "clips_summary.json").read_text())
    clips = cs["clips"]
    L = ["# intra_playback - generated tables", "",
         "Generated by `scripts/intra_playback/summarize_intra.py` from `results/intra_playback/functional/*/*.json` and "
         "`clips_summary.json`. Do not edit. No timing fields exist in these inputs.", ""]
    L += ["## Versions (measured: functional/<browser>/caps.json `versions`)", ""]
    for b, v in versions().items():
        L.append(f"- {b}: `{json.dumps(v)}`")
    L += ["", "## Clips (measured: clips_summary.json; PyAV 19.0.2 encode, ffprobe 9.0.2 inspection)", "",
          "| clip | codec string | frames | key (container) | IDR frames | non-IRAP VCL frames | ffprobe key / pict | has_b | bytes/frame | q | decode-back pattern | Y-PSNR dB | Y-SSIM |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, c in clips.items():
        if c.get("kind") not in ("video", "mjpeg"):
            continue
        nc = c.get("nal_check") or {}
        fp = c.get("ffprobe") or {}
        st = fp.get("stream") or {}
        dq = c.get("decode_check_mp4") if isinstance(c.get("decode_check_mp4"), dict) else c.get("decode_check") or {}
        L.append(f"| {k} | `{c.get('codec_string', c.get('codec'))}` | {c.get('frames')} | {c.get('keyframe_count')} | {nc.get('frames_with_idr', '')} | "
                 f"{nc.get('frames_with_non_irap_vcl', '')} | {fp.get('key_frames', '')}/{fp.get('frames', '')} {json.dumps(fp.get('pict_types', '')).replace(' ', '')} | "
                 f"{st.get('has_b_frames', '')} | {round(c['bytes'] / max(1, c['frames']))} | {c.get('quality_param', '')} | "
                 f"{dq.get('pattern_ok', '')}/{dq.get('decoded', '')} | {dq.get('y_psnr_db_mean', '')} | {dq.get('y_ssim_mean', '')} |")
    # calibration
    L += ["", "## Quality calibration (measured: clips_summary.json `calibration`; 30 frames, Y-PSNR in limited-range units)", "",
          "| encoder / height / corpus set | chosen q | sweep (q: dB, bytes/frame) |", "|---|---|---|"]
    for k, c in cs.get("calibration", {}).items():
        sw = "; ".join(f"{s['q']}: {s.get('y_psnr_db')}, {round(s.get('bytes_per_frame', 0))}" for s in c.get("sweep", []) if "y_psnr_db" in s)
        L.append(f"| {k} | {c.get('chosen_q')} | {sw} |")
    # seek / step / play per clip
    for kind, prefix in [("Random paused seeks", "seek_"), ("Single-frame steps (20 forward, 40 back, from random starts)", "step_"), ("Playback pattern check (N=1, 5 s)", "play_")]:
        L += ["", f"## {kind} (measured: functional/<browser>/{prefix}<content>.json)", ""]
        rows = defaultdict(dict)
        for b in BROWSERS:
            for x in load(b, prefix):
                c, r = x["config"], x["result"]
                tag = c.get("path", "") + (f":{c['mode']}" if c.get("mode") else "") + (":flush" if c.get("wcflush") == "1" else "")
                if prefix == "play_":
                    if isinstance(r, dict) and "per_stream" in r:
                        ps = r["per_stream"][0]
                        n = ps.get("rvfc_callbacks", ps.get("draws"))
                        cell = f"{n} frames, mismatch {ps.get('pattern_mismatch')}"
                    else:
                        cell = "X: " + str((r or {}).get("error", r))[:70]
                else:
                    cell = cell_seek(r)
                dn = dec_names(r)
                rows[(c.get("clip"), tag)][b] = cell + (f" [{dn}]" if dn else "")
        L += ["| clip | path | " + " | ".join(BROWSERS) + " |", "|---|---|" + "---|" * len(BROWSERS)]
        for (clip, tag), v in sorted(rows.items(), key=lambda kv: (str(kv[0][0]), kv[0][1])):
            L.append(f"| {clip} | {tag} | " + " | ".join(v.get(b, "-") for b in BROWSERS) + " |")
    # compact pivot: one row per family/container/timing, cells "e35 | e45 | c156"
    piv = defaultdict(lambda: defaultdict(lambda: defaultdict(lambda: [0, 0, 0])))  # row -> col -> browser -> [exact, n, flushes]
    decs = defaultdict(lambda: defaultdict(set))
    for b in BROWSERS:
        for prefix in ["seek_", "step_", "play_"]:
            for x in load(b, prefix):
                c, r = x["config"], x["result"]
                clip = c.get("clip", "")
                meta = clips.get(clip, {})
                fam = clip.split("/")[1].split("_intra")[0] if "_intra" in clip else clip.split("/")[1]
                cont = "fmp4" if "_frag" in clip else ("mkv" if clip.endswith(".mkv") or "in_mkv" in clip else ("mp4" if clip.endswith(".mp4") else "mjpeg"))
                row = (fam, cont, "VFR" if meta.get("vfr") else "CFR")
                col = prefix[:-1] + ":" + c.get("path", "") + (f":{c['mode']}" if c.get("mode") else "") + (":flush" if c.get("wcflush") == "1" else "")
                cell = piv[row][col][b]
                if isinstance(r, dict) and "summary" in r:
                    cell[0] += r["summary"]["exact"]; cell[1] += r["summary"]["n"]; cell[2] += r["summary"].get("flushes") or 0
                elif isinstance(r, dict) and "per_stream" in r:
                    ps = r["per_stream"][0]
                    n = ps.get("rvfc_callbacks", ps.get("draws")) or 0
                    cell[0] += n - (ps.get("pattern_mismatch") or 0); cell[1] += n
                else:
                    cell[1] += 0; cell[2] -= 1000  # error marker
                dn = dec_names(r)
                if dn:
                    decs[(fam, c.get("path", ""))][b].add(dn)
    cols = ["seek:video:cfrmid", "seek:video:mid", "seek:webcodecs:flush", "seek:webcodecs", "seek:webcodecs-hw", "seek:webcodecs-sw",
            "step:video:mid", "step:webcodecs:flush", "play:video-free", "play:wc-master",
            "seek:jpeg-range-bitmap", "seek:jpeg-range-imagedecoder", "step:jpeg-range-bitmap", "step:jpeg-range-imagedecoder", "play:jpeg-master-range-bitmap"]
    def fmt(v, col):
        out = []
        for b in BROWSERS:
            if b not in v:
                out.append("-"); continue
            e, n, fl = v[b]
            if fl <= -1000:
                out.append("X")
            else:
                out.append(f"{e}/{n}" + (f" fl{fl}" if col == "seek:webcodecs" else ""))
        return " \\| ".join(out)
    L += ["", "## Compact pivot (exact / total, cells = e35 | e45 | c156; play = frames whose pattern matched / frames shown; "
          "`seek:webcodecs` = no forced flush, `fl` = frames that only came out after the 200 ms fallback flush; X = error)", ""]
    for part, cs_ in [("H.264 / HEVC", [c_ for c_ in cols if "jpeg" not in c_]), ("JPEG path", [c_ for c_ in cols if "jpeg" in c_ or c_ == "seek:video:mid"])]:
        rows_ = [r_ for r_ in sorted(piv) if (part == "JPEG path") == (r_[0] in ("jpeg_seq", "jpeg_in_mkv", "mjpeg_qsv422.mkv"))]
        L += [f"### {part}", "", "| family | container | timing | " + " | ".join(cs_) + " |", "|---|---|---|" + "---|" * len(cs_)]
        for r_ in rows_:
            L.append("| " + " | ".join(r_) + " | " + " | ".join(fmt(piv[r_][c_], c_) if c_ in piv[r_] else "" for c_ in cs_) + " |")
        L.append("")
    L += ["## Decoder names reported by the Media domain (kVideoDecoderName), per family and path", "",
          "| family | path | " + " | ".join(BROWSERS) + " |", "|---|---|" + "---|" * len(BROWSERS)]
    for k_, v in sorted(decs.items()):
        L.append(f"| {k_[0]} | {k_[1]} | " + " | ".join("; ".join(sorted(v.get(b, []))) or "-" for b in BROWSERS) + " |")
    # JPEG-in-MKV byte identity
    L += ["", "## Camera JPEG bytes inside MKV, fetched by byte range (measured: functional/<browser>/jpegmkv_*.json)", "",
          "| browser | order | tested | HTTP 206 fetches | bytes identical to corpus file | SOI/EOI ok | createImageBitmap ok | ImageDecoder ok | errors |",
          "|---|---|---|---|---|---|---|---|---|"]
    for b in BROWSERS:
        for x in load(b, "jpegmkv_"):
            for clip, r in (x["result"] or {}).items():
                if not isinstance(r, dict):
                    continue
                L.append(f"| {b} | {r.get('order')} | {r.get('tested')} | {r.get('range_fetches')} | {r.get('bytes_identical')} | {r.get('soi_eoi_ok')} | "
                         f"{r.get('bitmap_ok')} | {r.get('imagedecoder_ok')} | {'; '.join(r.get('errors', []))[:120]} |")
    # caps
    L += ["", "## API probes (measured: functional/<browser>/caps.json)", "",
          "| container / codec | browser | canPlayType | MSE | MC 1080p30 | WC 1080p prefer-hardware | WC 1080p prefer-software |", "|---|---|---|---|---|---|---|"]
    for b in BROWSERS:
        f = R / "functional" / b / "caps.json"
        if not f.exists():
            continue
        d = json.loads(f.read_text())["result"]
        for row in d.get("codecs", []):
            L.append(f"| {row['container']} `{row['codec']}` | {b} | {row.get('canPlayType')} | {row.get('mseIsTypeSupported')} | {row.get('mc_1080p30')} | "
                     f"{row.get('wc_1080p30_prefer-hardware')} | {row.get('wc_1080p30_prefer-software')} |")
    # sync4 smoke
    L += ["", "## N=4 sync smoke of the bench paths (measured: functional/<browser>/sync4.json; pattern check only, no timing)", "",
          "| clip | path | browser | per-stream frames | pattern mismatches | other |", "|---|---|---|---|---|---|"]
    for b in BROWSERS:
        for x in load(b, "sync4"):
            c, r = x["config"], x["result"]
            if not isinstance(r, dict) or "per_stream" not in r:
                L.append(f"| {c.get('clip')} | {c.get('path')} | {b} | X | | {str((r or {}).get('error'))[:80]} |")
                continue
            fr = [s.get("rvfc_callbacks", s.get("draws")) for s in r["per_stream"]]
            mm = [s.get("pattern_mismatch") for s in r["per_stream"]]
            other = {k: r[k] for k in ("rvfc_hard_seeks", "rvfc_rate_changes", "follower_corrections") if k in r}
            L.append(f"| {c.get('clip')} | {c.get('path')} | {b} | {fr} | {mm} | {json.dumps(other)} |")
    (R / "functional_tables.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", R / "functional_tables.md")


if __name__ == "__main__":
    main()
